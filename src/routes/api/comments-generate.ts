import { createFileRoute } from "@tanstack/react-router";
import { createClient } from "@supabase/supabase-js";
import type { Database } from "@/integrations/supabase/types";

const LANGS: Record<string, string> = {
  gasy: "malgache 100% (aucun mot français)",
  fr: "français",
  mix: "mélange naturel malgache et français",
};
const THEMES: Record<string, string> = {
  anniversaire: "un anniversaire",
  vente: "une vente / un produit à vendre",
  felicitations: "des félicitations",
  humour: "une publication humoristique",
  custom: "la publication décrite",
};

// Streams plain text (one comment per line) generated by OpenAI.
export const Route = createFileRoute("/api/comments-generate")({
  server: {
    handlers: {
      POST: async ({ request }) => {
        const token = request.headers.get("authorization")?.replace(/^Bearer\s+/i, "") ?? "";
        if (!token) return new Response("Unauthorized", { status: 401 });
        const sb = createClient<Database>(process.env["SUPABASE_URL"]!, process.env["SUPABASE_PUBLISHABLE_KEY"]!, {
          auth: { persistSession: false, autoRefreshToken: false },
        });
        const { data: u } = await sb.auth.getUser(token);
        if (!u.user) return new Response("Unauthorized", { status: 401 });

        const apiKey = process.env["OPENAI_API_KEY"];
        if (!apiKey) return new Response("Clé OpenAI manquante", { status: 500 });

        let body: { count?: number; lang?: string; theme?: string; topic?: string; avoid?: string[] };
        try { body = await request.json(); } catch { return new Response("Bad request", { status: 400 }); }
        const count = Math.min(500, Math.max(1, Math.floor(Number(body.count) || 0)));
        const lang = LANGS[body.lang ?? ""] ?? LANGS["gasy"];
        const theme = THEMES[body.theme ?? ""] ?? THEMES["custom"];
        const topic = String(body.topic ?? "").slice(0, 300) || "(non précisé)";
        const avoid = (body.avoid ?? []).slice(-60).map((s) => String(s).slice(0, 80));

        const prompt = `Génère ${count} commentaires Facebook courts en ${lang} pour ${theme} à propos de ${topic}. Unique, naturel, 5-12 mots, 30% emoji, 1 par ligne.
Réponds uniquement avec les commentaires, sans numérotation, sans tirets, sans guillemets.${avoid.length ? `\nÉvite ceux-ci déjà utilisés :\n${avoid.join("\n")}` : ""}`;

        const res = await fetch("https://api.openai.com/v1/chat/completions", {
          method: "POST",
          signal: request.signal,
          headers: { "Content-Type": "application/json", Authorization: `Bearer ${apiKey}` },
          body: JSON.stringify({
            model: "gpt-4o-mini",
            stream: true,
            temperature: 1,
            messages: [{ role: "user", content: prompt }],
          }),
        });
        if (!res.ok || !res.body) {
          const txt = await res.text().catch(() => "");
          let msg = `Erreur OpenAI (${res.status})`;
          try { msg = JSON.parse(txt).error?.message ?? msg; } catch { /* ignore */ }
          return new Response(msg, { status: res.status === 429 ? 429 : 502 });
        }

        const decoder = new TextDecoder();
        const encoder = new TextEncoder();
        let buf = "";
        const stream = res.body.pipeThrough(
          new TransformStream<Uint8Array, Uint8Array>({
            transform(chunk, ctrl) {
              buf += decoder.decode(chunk, { stream: true });
              const lines = buf.split("\n");
              buf = lines.pop() ?? "";
              for (const line of lines) {
                if (!line.startsWith("data:")) continue;
                const raw = line.slice(5).trim();
                if (!raw || raw === "[DONE]") continue;
                try {
                  const d = JSON.parse(raw).choices?.[0]?.delta?.content;
                  if (typeof d === "string" && d) ctrl.enqueue(encoder.encode(d));
                } catch { /* partial */ }
              }
            },
          }),
        );
        return new Response(stream, {
          headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "no-cache, no-transform" },
        });
      },
    },
  },
});
